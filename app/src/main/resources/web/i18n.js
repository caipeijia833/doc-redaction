  function normalizeLocale(value) {
    const normalized = String(value || '').toLowerCase();
    if (normalized.startsWith('zh')) return 'zh-CN';
    if (normalized.startsWith('en')) return 'en';
    return 'zh-CN';
  }

  function initialLocale() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) return normalizeLocale(saved);
    } catch (_) {
      // A blocked storage API must not prevent the offline UI from loading.
    }
    return normalizeLocale(navigator.language || 'zh-CN');
  }

  let locale = initialLocale();

  function t(key, params = {}) {
    const table = { ...messages[locale], ...dynamic[locale] };
    const fallback = { ...messages['zh-CN'], ...dynamic['zh-CN'] };
    const template = table[key] ?? fallback[key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
  }

  function apply(root = document) {
    document.documentElement.lang = locale;
    root.querySelectorAll('[data-i18n]').forEach((node) => { node.textContent = t(node.dataset.i18n); });
    root.querySelectorAll('[data-i18n-value]').forEach((node) => {
      const key = node.dataset.i18nValue;
      const translatedDefaults = Object.values(messages).map((table) => table[key]).filter(Boolean);
      if (!node.dataset.i18nValueApplied || translatedDefaults.includes(node.value)) node.value = t(key);
      node.dataset.i18nValueApplied = 'true';
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
    root.querySelectorAll('[data-i18n-aria-label]').forEach((node) => { node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel)); });
    root.querySelectorAll('[data-language]').forEach((button) => {
      const active = normalizeLocale(button.dataset.language) === locale;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
  }

  function setLocale(value) {
    const next = normalizeLocale(value);
    if (next === locale) return;
    locale = next;
    try { localStorage.setItem(STORAGE_KEY, locale); } catch (_) { /* local-only preference is optional */ }
    apply();
    document.dispatchEvent(new CustomEvent('doc-redaction-language-change', { detail: { locale } }));
  }

  function ruleLabel(rule) {
    return locale === 'en' && rule?.source !== 'custom' ? (ruleLabels[rule.id] || rule.id) : (rule?.label || rule?.id || '');
  }

  function serverText(value) {
    if (locale !== 'en' || value == null || value === '') return String(value ?? '');
    const text = String(value);
    if (!/[\u3400-\u9fff]/u.test(text)) return text;
    if (serverExact[text]) return serverExact[text];
    for (const [pattern, replacement] of serverPatterns) {
      if (pattern.test(text)) return text.replace(pattern, replacement);
    }
    return 'The local service reported a technical message. Switch to Chinese or inspect the local audit record for the original detail.';
  }

  function currentLocale() { return locale; }
  function intlLocale() { return locale === 'zh-CN' ? 'zh-CN' : 'en-US'; }

  apply();
  return Object.freeze({ t, apply, setLocale, currentLocale, intlLocale, ruleLabel, serverText, normalizeLocale });
